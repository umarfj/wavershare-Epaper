"""Convert an image to a 240x416 1-bit C header for the WeAct 3.7" e-paper.
Usage: python tools/img2header.py "image copy.png" src/photo.h [preview.png] [contrast=1.6] [gamma=1.6]
Auto-trims dark screenshot borders, scales to cover 240x416 (crops, keeps top),
boosts contrast, Floyd-Steinberg dithers. Bit 1 = black (use drawBitmap with GxEPD_BLACK)."""
import sys
from PIL import Image, ImageOps, ImageEnhance
W, H = 240, 416
src, out = sys.argv[1], sys.argv[2]
prev = sys.argv[3] if len(sys.argv) > 3 else None
CONTRAST = float(sys.argv[4]) if len(sys.argv) > 4 else 1.6   # >1 = more contrast
GAMMA = float(sys.argv[5]) if len(sys.argv) > 5 else 1.6      # >1 = darker midtones
im = Image.open(src).convert("RGB")
# trim near-black border
g = im.convert("L").point(lambda p: 255 if p > 40 else 0)
bbox = g.getbbox()
if bbox: im = im.crop(bbox)
# trim any remaining thin dark edge rows/cols
im = im.crop((3, 3, im.width - 3, im.height - 3))
s = max(W / im.width, H / im.height)
im = im.resize((round(im.width * s), round(im.height * s)), Image.LANCZOS)
left = (im.width - W) // 2
im = im.crop((left, 0, left + W, H))           # keep top (faces), crop bottom
g = ImageOps.autocontrast(im.convert("L"), cutoff=1)
g = ImageEnhance.Contrast(g).enhance(CONTRAST)
g = g.point(lambda p: round(255 * (p / 255) ** GAMMA))
bw = g.convert("1", dither=Image.FLOYDSTEINBERG)  # 0 = black
if prev: bw.save(prev)
data = bytearray()
for y in range(H):
    for x in range(0, W, 8):
        b = 0
        for k in range(8):
            if bw.getpixel((x + k, y)) == 0: b |= 0x80 >> k
        data.append(b)
with open(out, "w") as f:
    f.write("// Generated by tools/img2header.py. %dx%d, bit 1 = black\n" % (W, H))
    f.write("#pragma once\n#include <Arduino.h>\nconst uint8_t PHOTO_BMP[] PROGMEM = {\n")
    for i in range(0, len(data), 16):
        f.write("  " + ",".join("0x%02X" % v for v in data[i:i+16]) + ",\n")
    f.write("};\n")
print("wrote", out, len(data), "bytes")
